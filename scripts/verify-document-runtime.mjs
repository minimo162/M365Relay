import assert from 'node:assert/strict';
import {writeFile,readFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const [appArg,workArg]=process.argv.slice(2);
assert(appArg&&workArg,'Pass extracted application and test directory');
const app=resolve(appArg),work=resolve(workArg);
const env={...process.env,NODE_OPTIONS:'',NODE_PATH:'',OFFICECLI_SKIP_UPDATE:'1',OFFICECLI_NO_AUTO_RESIDENT:'1'};
const run=(exe,args)=>execFileSync(exe,args,{encoding:'utf8',env,timeout:20000,windowsHide:true});

// A minimal, deterministic PDF with a correct xref, without fixture libraries.
const content='BT /F1 12 Tf 40 100 Td (RUNTIME-CHECK 17.50) Tj ET';
const objects=['<< /Type /Catalog /Pages 2 0 R >>','<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
 '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 300 200] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
 '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',`<< /Length ${content.length} >>\nstream\n${content}\nendstream`];
let pdf='%PDF-1.4\n',offsets=[0];
for(const [i,body] of objects.entries()){offsets.push(Buffer.byteLength(pdf));pdf+=`${i+1} 0 obj\n${body}\nendobj\n`;}
const xref=Buffer.byteLength(pdf);pdf+=`xref\n0 6\n0000000000 65535 f \n${offsets.slice(1).map(n=>`${String(n).padStart(10,'0')} 00000 n \n`).join('')}trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
const input=join(work,'document-runtime.pdf'),output=join(work,'document-runtime.json');
await writeFile(input,pdf,{flag:'wx'});
const original=createHash('sha256').update(await readFile(input)).digest('hex');
const pdfArgs=[join(app,'src','pdf-cli.mjs'),input,output,'1'];
run(process.execPath,pdfArgs);
const result=JSON.parse(await readFile(output,'utf8'));
assert.equal(result.totalPages,1);assert.equal(result.ocrEnabled,false);
assert.equal(result.selectionComplete,true);assert.deepEqual(result.pagesWithoutText,[]);
assert(result.pages[0].text.includes('RUNTIME-CHECK'));assert(result.pages[0].textItems.every(i=>Number.isFinite(i.x)&&Number.isFinite(i.y)));
assert(result.markdown.includes('17.50'));
const outputBytes=await readFile(output);
assert.throws(()=>run(process.execPath,pdfArgs));
assert.deepEqual(await readFile(output),outputBytes);
assert.equal(createHash('sha256').update(await readFile(input)).digest('hex'),original);
const blankInput=join(work,'blank.pdf'),blankOutput=join(work,'blank.json');
await writeFile(blankInput,pdf.replace('RUNTIME-CHECK 17.50',' '.repeat('RUNTIME-CHECK 17.50'.length)),{flag:'wx'});
run(process.execPath,[pdfArgs[0],blankInput,blankOutput]);
const blank=JSON.parse(await readFile(blankOutput,'utf8'));
assert.equal(blank.selectionComplete,true);assert.deepEqual(blank.pagesWithoutText,[1]);
assert(blank.warnings.some(w=>w.code==='no_text_extracted'));
const outside=join(work,'outside.json');
assert.throws(()=>run(process.execPath,[pdfArgs[0],input,outside,'2']));
await assert.rejects(readFile(outside),{code:'ENOENT'});


const python=join(app,'runtime/python/python.exe'),document=join(app,'python/document_runtime.py');
const textResult=JSON.parse(run(python,['-I','-B',document,'pdf-text',input]));
assert.equal(textResult.totalPages,1);
assert.equal(textResult.documentComplete,true);
assert.deepEqual(textResult.parsedPageNumbers,[1]);
assert.equal(textResult.pages[0].text,result.pages[0].text);
assert.equal('textItems' in textResult.pages[0],false);
const blankText=JSON.parse(run(python,['-I','-B',document,'pdf-text',blankInput]));
assert.deepEqual(blankText.pagesWithoutText,[1]);
assert.equal(blankText.ocrEnabled,false);
assert.throws(()=>run(python,['-I','-B',document,'pdf-text',input,'--pages','2']));
const multiInput=join(work,'six-pages.pdf');
run(python,['-I','-B','-c','import sys; from pypdf import PdfReader,PdfWriter; r=PdfReader(sys.argv[1]); w=PdfWriter(); [w.add_page(r.pages[0]) for _ in range(6)]; w.write(sys.argv[2])',input,multiInput]);
const partialText=JSON.parse(run(python,['-I','-B',document,'pdf-text',multiInput]));
assert.equal(partialText.totalPages,6);
assert.equal(partialText.documentComplete,false);
assert.deepEqual(partialText.parsedPageNumbers,[1,2,3,4,5]);
const lastText=JSON.parse(run(python,['-I','-B',document,'pdf-text',multiInput,'--pages','6']));
assert.deepEqual(lastText.parsedPageNumbers,[6]);
assert.equal(lastText.pages[0].text,result.pages[0].text);
const doc=(...args)=>JSON.parse(run(python,['-I','-B',document,...args]));
assert.equal(doc('pdf-read',input).parser,'pypdfium2');
const savedPdf=join(work,'python-pdf-read.json');
const savedSummary=doc('pdf-read',input,savedPdf);
assert.equal(savedSummary.output,resolve(savedPdf));
assert.deepEqual(JSON.parse(await readFile(savedPdf,'utf8')),doc('pdf-read',input));
const savedBytes=await readFile(savedPdf);
assert.throws(()=>doc('pdf-read',input,savedPdf));
assert.deepEqual(await readFile(savedPdf),savedBytes);
const invalidSaved=join(work,'invalid-python-pdf.json');
assert.throws(()=>doc('pdf-read',input,invalidSaved,'--pages','2'));
await assert.rejects(readFile(invalidSaved),{code:'ENOENT'});
const png=join(work,'preview.png');doc('pdf-render',input,png);
assert.deepEqual((await readFile(png)).subarray(0,8),Buffer.from([137,80,78,71,13,10,26,10]));
assert.throws(()=>doc('pdf-render',input,png));
const literalValues=['Literal <tag> &gt; "quoted"','  日本語😀 C:\\new\\notes.txt \\n  ','line1\nline2\tend','00123','=SUM(A1:A2)'];
const dataPath=join(work,'cells.json'),sheet=join(work,'document-runtime.xlsx');
const cells={A1:{value:1.5},A2:{value:2},A3:{formula:'SUM(A1:A2)'}};
for(const [i,value]of literalValues.entries())cells[`B${i+1}`]={value};
await writeFile(dataPath,JSON.stringify({sheet:'Sheet1',cells}),{flag:'wx'});
const created=doc('xlsx-create',sheet,dataPath);assert.equal(created.formulasCalculated,false);
const readback=doc('xlsx-read',sheet).sheets[0].cells;
assert.equal(readback.find(c=>c.address==='A3').value,'=SUM(A1:A2)');
assert.equal(readback.find(c=>c.address==='A3').cachedValue,null);
for(const [i,value]of literalValues.entries())assert.equal(readback.find(c=>c.address===`B${i+1}`).value,value);
assert.throws(()=>doc('xlsx-create',sheet,dataPath));
